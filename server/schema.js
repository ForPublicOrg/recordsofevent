// Idempotent schema. Bump SCHEMA_VERSION after changing it; it runs once on the next cold start.
export const SCHEMA_VERSION = '4';

export const SCHEMA = `
create table if not exists meta (k text primary key, v text not null);

create table if not exists events (
  id integer generated by default as identity primary key,
  slug text not null unique,
  code text not null unique,
  title text not null,
  kind text not null default 'Protest',
  date text not null,
  tz text not null default 'UTC',
  city text not null default '',
  country text not null default '',
  aliases text[] not null default '{}',
  summary text not null default '',
  figures jsonb,
  sources jsonb not null default '[]',
  color text not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  ip text
);
create index if not exists events_status_date on events (status, date desc);

create table if not exists places (
  id integer generated by default as identity primary key,
  event_id integer not null references events (id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists places_event_name on places (event_id, lower(name));

create table if not exists batches (
  id integer generated by default as identity primary key,
  token text not null unique,
  event_id integer not null references events (id) on delete cascade,
  created_at timestamptz not null default now(),
  ip text
);

create table if not exists clips (
  id integer generated by default as identity primary key,
  record text unique,
  event_id integer not null references events (id) on delete cascade,
  batch_id integer references batches (id) on delete set null,
  place_id integer references places (id) on delete set null,
  status text not null default 'uploading',
  label text not null default 'unverified',
  sensitive boolean not null default false,
  note text not null default '',
  name text not null default '',
  captured_at timestamptz not null,
  time_source text not null default 'file',
  duration double precision,
  width integer,
  height integer,
  size double precision not null,
  mime text not null default '',
  sha256 text,
  sha256_original text,
  stripped text[] not null default '{}',
  storage_key text not null,
  poster_key text,
  has_poster boolean not null default false,
  upload_id text,
  reason text not null default '',
  created_at timestamptz not null default now(),
  published_at timestamptz,
  ip text
);
create index if not exists clips_event on clips (event_id, status, captured_at);
create index if not exists clips_status on clips (status, created_at);
create index if not exists clips_sha on clips (sha256);
create index if not exists clips_sha_original on clips (sha256_original);
create index if not exists clips_place on clips (place_id) where status = 'published';
create index if not exists clips_published on clips (published_at desc) where status = 'published';
create index if not exists clips_ip on clips (ip, created_at);
create index if not exists clips_batch on clips (batch_id);

create table if not exists reports (
  id integer generated by default as identity primary key,
  ref text not null unique,
  clip_id integer references clips (id) on delete set null,
  event_id integer references events (id) on delete set null,
  reason text not null,
  details text not null default '',
  contact text not null default '',
  status text not null default 'open',
  resolution text not null default '',
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  ip text
);
create index if not exists reports_status on reports (status, created_at);
create index if not exists reports_clip on reports (clip_id, status);

create table if not exists counters (k text primary key, n integer not null);
create table if not exists hits (k text not null, w bigint not null, n integer not null default 1, primary key (k, w));
create table if not exists modlog (
  id integer generated by default as identity primary key,
  at timestamptz not null default now(),
  actor text not null,
  action text not null,
  target text not null,
  detail jsonb
);

-- Copy progress for a video added by link (source, next part, part ETags, saved hash states).
alter table clips add column if not exists link_job jsonb;

-- Repair: an earlier version stored some jsonb values as JSON strings (double-encoded).
update events set sources = (sources #>> '{}')::jsonb where jsonb_typeof(sources) = 'string';
update events set figures = (figures #>> '{}')::jsonb where jsonb_typeof(figures) = 'string';
update modlog set detail = (detail #>> '{}')::jsonb where jsonb_typeof(detail) = 'string';
update clips set link_job = (link_job #>> '{}')::jsonb where jsonb_typeof(link_job) = 'string';
`;
